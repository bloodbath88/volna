"""Обновляет заметки к релизу: заголовок 1.1.1 и раздел «что нового»."""
import io
import re

path = "deploy/release-notes.md"
with io.open(path, encoding="utf-8", newline="") as fh:
    text = fh.read()

text = text.replace("# Волна 1.1 — сборки", "# Волна 1.1.1 — сборки", 1)

new_block = (
    "## Что нового в 1.1.1\n"
    "\n"
    "- **Исправлено соединение через интернет на VPS.** Голосовое ядро теперь определяет внешний\n"
    "  адрес само (`use_external_ip: true`) вместо жёстко прописанного IP. Комбинация «`node_ip`\n"
    "  + `use_external_ip: false`» на сервере с публичным адресом `/32` (типичный VPS за NAT\n"
    "  провайдера) приводила к ошибке `could not establish pc connection`. Проверено на живом\n"
    "  сервере: вход по паролю и по ссылке-приглашению устанавливают соединение.\n"
    "- **Ссылка-приглашение.** Код разбирается, даже если при копировании добавились пробел,\n"
    "  перевод строки или кавычки; если вход по ссылке не удался — приложение раскрывает поле\n"
    "  пароля и пишет, что ссылка могла обрезаться.\n"
    "\n"
)

marker = "## Что нового в 1.1"
if "## Что нового в 1.1.1" not in text:
    text = text.replace(marker, new_block + "## Что было в 1.1", 1)

with io.open(path, "w", encoding="utf-8", newline="") as fh:
    fh.write(text)

print("заголовок 1.1.1:", text.splitlines()[0])
print("раздел 1.1.1 добавлен:", "## Что нового в 1.1.1" in text)
