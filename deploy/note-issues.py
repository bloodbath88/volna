"""Записывает в UI-STATE.md известные ошибки, о которых просил пользователь."""
import io

PATH = "deploy/UI-STATE.md"
BLOCK = """
## Известные ошибки и что с ними сделано (22.10.2026, после v1.7.3)

1. **«Не удалось войти: could not establish signal connection: room connection has timed out (signal)»**
   - Комната была названа `main-новая-тестовая` — кириллица в имени комнаты.
   - Сделано: имя комнаты теперь транслитерируется в латиницу (`main-novaya-testovaya`), кириллица
     больше не попадает в токен и в код приглашения.
   - Если повторится на латинском имени — смотреть `run/server.out.log` (ответ `/api/token`) и
     доступность сигнального порта 7880; возможен rate-limit на частые входы.
2. **Долгий вход в приложение.**
   - Причина частично в сбросе HTTP-кэша при каждом запуске (добавлено в v1.7.3).
   - Сделано: сброс теперь не чаще одного раза в 24 часа (`cache-stamp.json` в userData).
3. **Чёрный экран при переходе из комнаты в комнату** (видна только плашка «Переход в комнату…»).
   - Причина: при выходе сцена скрывалась и до подключения новой комнаты показывать было нечего.
   - Сделано: во время перехода сцена не скрывается — последний кадр остаётся под плашкой.

Проверка после деплоя: версия ассетов `?v=20261022f`, `entry.js` на сервере совпадает с локальным
по SHA-256 (`5083ce85…`).
"""

with io.open(PATH, "a", encoding="utf-8", newline="") as fh:
    fh.write(BLOCK)

print("ошибки записаны")
